"""
Emits sql/01_schema.sql.

The Elliptic feature table is 165 columns wide (93 local + 72 aggregate). Writing
those column definitions by hand invites typos and drift between the DDL, the
staging table, and the COPY column list, so all three are generated from one
constant here.
"""
from pathlib import Path

N_LOCAL = 93
N_AGG = 72

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "sql" / "01_schema.sql"

local_cols = [f"local_feature_{i}" for i in range(1, N_LOCAL + 1)]
agg_cols = [f"aggregate_feature_{i}" for i in range(1, N_AGG + 1)]
feature_cols = local_cols + agg_cols


def col_block(cols, indent="    "):
    return ",\n".join(f"{indent}{c:<26} DOUBLE PRECISION NOT NULL" for c in cols)


HEADER = """-- ============================================================================
-- ANLC-752 Course Project -- Physical schema
-- Bitcoin transaction AML monitoring database (Elliptic Data Set)
--
-- Target platform: PostgreSQL 14+
-- Generated by etl/gen_schema.py -- edit the generator, not this file.
--
-- Layer model:
--   staging    volatile landing zone, text-typed, no constraints
--   core       conformed, constrained, referentially complete
--   analytics  derived AML monitoring objects (views / materialized views)
--   governance ETL audit trail and data quality results
-- ============================================================================

DROP SCHEMA IF EXISTS staging    CASCADE;
DROP SCHEMA IF EXISTS analytics  CASCADE;
DROP SCHEMA IF EXISTS core       CASCADE;
DROP SCHEMA IF EXISTS governance CASCADE;

CREATE SCHEMA staging;
CREATE SCHEMA core;
CREATE SCHEMA analytics;
CREATE SCHEMA governance;

COMMENT ON SCHEMA staging    IS 'Landing zone. Text-typed, truncated each run. Never queried by analysts.';
COMMENT ON SCHEMA core       IS 'Conformed transaction, flow and feature data with enforced integrity.';
COMMENT ON SCHEMA analytics  IS 'Derived AML monitoring layer. Read-only to the analyst role.';
COMMENT ON SCHEMA governance IS 'Load audit trail and data quality rule results.';


-- ============================================================================
-- 1. REFERENCE / DIMENSION TABLES
-- ============================================================================

CREATE TABLE core.dim_class (
    class_id        SMALLINT     PRIMARY KEY,
    class_code      VARCHAR(16)  NOT NULL UNIQUE,
    class_label     VARCHAR(64)  NOT NULL,
    is_labelled     BOOLEAN      NOT NULL,
    description     TEXT
);

COMMENT ON TABLE core.dim_class IS
    'Ground-truth classification assigned by Elliptic Ltd. Class 3 (unknown) is an '
    'absence of label, not a third outcome -- is_labelled makes that explicit so '
    'analysts cannot silently treat unknown as licit.';

INSERT INTO core.dim_class (class_id, class_code, class_label, is_labelled, description) VALUES
    (1, 'illicit', 'Illicit',  TRUE,
        'Transaction attributed to an entity in a category Elliptic classifies as illicit '
        '(scams, malware, terrorist organisations, ransomware, Ponzi schemes).'),
    (2, 'licit',   'Licit',    TRUE,
        'Transaction attributed to a lawful entity (exchanges, wallet providers, miners, '
        'licensed financial providers).'),
    (3, 'unknown', 'Unlabelled', FALSE,
        'No ground-truth label available. Excluded from supervised scope; retained because '
        'these transactions still carry money flow relevant to graph-based monitoring.');


CREATE TABLE core.dim_time_step (
    time_step        SMALLINT PRIMARY KEY
        CONSTRAINT ck_time_step_range CHECK (time_step BETWEEN 1 AND 49),
    nominal_interval VARCHAR(32) NOT NULL DEFAULT 'approx. 2 weeks',
    description      TEXT
);

COMMENT ON TABLE core.dim_time_step IS
    'The 49 discrete time steps of the dataset. Each is a connected component of '
    'transactions appearing on the blockchain within roughly a two-week window; '
    'steps are evenly spaced but carry no absolute calendar date.';


CREATE TABLE core.dim_feature (
    feature_id      SMALLINT     PRIMARY KEY,
    column_name     VARCHAR(64)  NOT NULL UNIQUE,
    feature_group   VARCHAR(16)  NOT NULL
        CONSTRAINT ck_feature_group CHECK (feature_group IN ('local', 'aggregate')),
    ordinal_in_group SMALLINT    NOT NULL,
    is_obfuscated   BOOLEAN      NOT NULL DEFAULT TRUE,
    description     TEXT,
    CONSTRAINT uq_feature_group_ordinal UNIQUE (feature_group, ordinal_in_group)
);

COMMENT ON TABLE core.dim_feature IS
    'Catalogue of the 165 anonymised node features. Carries the lineage and '
    'interpretability caveat: is_obfuscated records that no feature can be mapped '
    'back to a real-world transaction attribute such as value or fee.';


-- ============================================================================
-- 2. CORE FACT TABLES
-- ============================================================================

CREATE TABLE core.transaction (
    tx_id        BIGINT   PRIMARY KEY,
    time_step    SMALLINT NOT NULL
        REFERENCES core.dim_time_step (time_step),
    class_id     SMALLINT NOT NULL
        REFERENCES core.dim_class (class_id),
    load_batch_id INTEGER NOT NULL
);

COMMENT ON TABLE core.transaction IS
    'One row per Bitcoin transaction (graph node). tx_id is the Elliptic surrogate '
    'identifier, not a Bitcoin transaction hash.';


CREATE TABLE core.tx_flow (
    src_tx_id     BIGINT NOT NULL REFERENCES core.transaction (tx_id),
    dst_tx_id     BIGINT NOT NULL REFERENCES core.transaction (tx_id),
    load_batch_id INTEGER NOT NULL,
    CONSTRAINT pk_tx_flow PRIMARY KEY (src_tx_id, dst_tx_id),
    CONSTRAINT ck_tx_flow_no_self_loop CHECK (src_tx_id <> dst_tx_id)
);

COMMENT ON TABLE core.tx_flow IS
    'Directed money flow edge: bitcoin from src_tx_id was spent by dst_tx_id. '
    'Edges connect transactions, NOT wallets or account holders -- the dataset '
    'carries no party or counterparty entity.';


CREATE TABLE core.tx_feature (
    tx_id BIGINT PRIMARY KEY REFERENCES core.transaction (tx_id),
{FEATURE_COLS}
);

COMMENT ON TABLE core.tx_feature IS
    'Wide 1:1 feature vector per transaction. A narrow (entity-attribute-value) '
    'design was rejected: it would turn 203,769 rows into ~33.6M and force a pivot '
    'on every analytical query, for no gain given a fixed, non-sparse feature set.';


-- ============================================================================
-- 3. GOVERNANCE
-- ============================================================================

CREATE TABLE governance.etl_load_audit (
    load_batch_id   SERIAL PRIMARY KEY,
    source_file     VARCHAR(128) NOT NULL,
    source_bytes    BIGINT,
    source_sha256   CHAR(64),
    target_table    VARCHAR(128) NOT NULL,
    rows_extracted  BIGINT,
    rows_rejected   BIGINT DEFAULT 0,
    rows_loaded     BIGINT,
    started_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at     TIMESTAMPTZ,
    status          VARCHAR(16) NOT NULL DEFAULT 'RUNNING'
        CONSTRAINT ck_load_status CHECK (status IN ('RUNNING','SUCCESS','FAILED')),
    notes           TEXT
);

COMMENT ON TABLE governance.etl_load_audit IS
    'One row per file-to-table load. source_sha256 pins the exact input artefact so '
    'a result can be traced back to the file that produced it.';


CREATE TABLE governance.dq_check_result (
    check_result_id SERIAL PRIMARY KEY,
    load_batch_id   INTEGER REFERENCES governance.etl_load_audit (load_batch_id),
    check_name      VARCHAR(128) NOT NULL,
    check_type      VARCHAR(32)  NOT NULL
        CONSTRAINT ck_dq_type CHECK (check_type IN
            ('completeness','uniqueness','referential','domain','reconciliation')),
    severity        VARCHAR(16)  NOT NULL
        CONSTRAINT ck_dq_severity CHECK (severity IN ('INFO','WARN','ERROR')),
    expected_value  TEXT,
    actual_value    TEXT,
    passed          BOOLEAN NOT NULL,
    checked_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE governance.dq_check_result IS
    'Outcome of each declarative data quality rule. Rules that fail with severity '
    'ERROR abort the load before core tables are touched.';


CREATE TABLE governance.rejected_row (
    rejected_row_id BIGSERIAL PRIMARY KEY,
    load_batch_id   INTEGER REFERENCES governance.etl_load_audit (load_batch_id),
    source_file     VARCHAR(128),
    source_line_no  BIGINT,
    reject_reason   VARCHAR(256) NOT NULL,
    raw_payload     TEXT
);

COMMENT ON TABLE governance.rejected_row IS
    'Quarantine for rows failing transformation or integrity rules. Rejects are '
    'retained rather than dropped so that data loss is visible and auditable.';


-- ============================================================================
-- 4. STAGING (text-typed landing zone, no constraints)
-- ============================================================================

CREATE UNLOGGED TABLE staging.txs_classes (
    tx_id      TEXT,
    class_code TEXT
);

CREATE UNLOGGED TABLE staging.txs_edgelist (
    src_tx_id TEXT,
    dst_tx_id TEXT
);

CREATE UNLOGGED TABLE staging.txs_features (
    tx_id     TEXT,
    time_step TEXT,
{STAGING_FEATURE_COLS}
);

COMMENT ON TABLE staging.txs_features IS
    'Landing table for the 167-column feature file. Every column is TEXT so that a '
    'malformed value fails a documented data quality rule instead of aborting COPY.';
"""


def main() -> None:
    sql = (
        HEADER
        .replace("{FEATURE_COLS}", col_block(feature_cols))
        .replace(
            "{STAGING_FEATURE_COLS}",
            ",\n".join(f"    {c:<26} TEXT" for c in feature_cols),
        )
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(sql)
    print(f"wrote {OUT} ({len(sql):,} chars, {len(feature_cols)} feature columns)")


if __name__ == "__main__":
    main()
